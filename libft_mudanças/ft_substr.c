#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*substr;
	size_t	copy_index;
	size_t	s_len;

	if (!s)
		return (NULL);
	s_len = ft_strlen(s);
	if (start >= s_len)
		len = 0;
	else if (len > s_len - start)
		len = s_len - start;
	substr = malloc(len + 1);
	if (!substr)
		return (NULL);
	copy_index = 0;
	while (copy_index < len)
	{
		substr[copy_index] = s[start + copy_index];
		copy_index++;
	}
	substr[copy_index] = '\0';
	return (substr);
}
